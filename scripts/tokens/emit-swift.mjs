/**
 * Swift emitter (ADR 0016) — the `PDSTokens` module: value types, one generated struct per
 * token group, and one `DSTheme` per brand, from the native model (scripts/tokens/native.mjs).
 *
 * Swift standard library only (no Foundation / SwiftUI import), so the generated module
 * type-checks on any Swift toolchain, including Linux CI. SwiftUI adapters (Color, Font,
 * Animation, shapes) belong to PDSUI (Phase 5):
 *
 *   color       DSColorValue(rgba: 0xRRGGBBAA)
 *   space, radius, icon   Double (pt); `radius.full` → DSCornerShape.full (a Capsule)
 *   typography  DSTextStyle — PostScript face, size, lineHeight, lineSpacing (size × (ratio − 1)),
 *               tracking (em × size) and the Dynamic Type anchor (`textScale`) for
 *               Font.custom(_:size:relativeTo:)
 *   elevation   DSShadow? — radius = blur ÷ 2, opacity = color alpha, spread dropped; nil = flat
 *   motion      DSTransition — seconds + cubic-bezier control points
 *   fonts       DSFontFamily per font role (asset metadata; no font files)
 */
import { isGroup, pascal, r4, walk } from './native.mjs';

const HEADER = `// Generated by scripts/tokens/emit-swift.mjs from the token IR — do not edit.
// PDSTokens: semantic and component-scoped tokens only; Core and brand.* tokens stay internal
// (ADR 0013, 0014, 0016). Source: src/tokens/. Rebuild: npm run tokens:build.
`;

const KEYWORDS = new Set(
  'associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self Self super throws true try'.split(
    ' ',
  ),
);
const id = (name) => (KEYWORDS.has(name) ? `\`${name}\`` : name);
const str = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const doc = (text, indent) =>
  text ? `${indent}/// ${String(text).replace(/\s+/g, ' ').trim()}\n` : '';
const hex32 = (n) => `0x${n.toString(16).toUpperCase().padStart(8, '0')}`;
const brandConst = (brand) => brand.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const typeName = (path) => (path.length ? `DS${path.map(pascal).join('')}` : 'DSTheme');

function leafType(leaf) {
  switch (leaf.kind) {
    case 'color':
      return 'DSColorValue';
    case 'dimension':
      return 'Double';
    case 'shape':
      return 'DSCornerShape';
    case 'textStyle':
      return 'DSTextStyle';
    case 'elevation':
      return 'DSShadow?';
    case 'transition':
      return 'DSTransition';
    case 'fontFamily':
      return 'DSFontFamily';
    default:
      throw new Error(`no Swift type for ${leaf.kind}`);
  }
}

function leafValue(leaf, indent) {
  switch (leaf.kind) {
    case 'color':
      return `DSColorValue(rgba: ${hex32(leaf.rgba)})`;
    case 'dimension':
      return String(leaf.value);
    case 'shape':
      return `.${leaf.shape}`;
    case 'textStyle':
      return `DSTextStyle(fontFamily: ${str(leaf.fontFamily)}, postScriptName: ${str(leaf.postScriptName)}, fontWeight: ${leaf.fontWeight}, size: ${leaf.fontSize}, lineHeight: ${leaf.lineHeight}, lineSpacing: ${leaf.lineSpacing}, letterSpacing: ${leaf.letterSpacingEm}, tracking: ${leaf.letterSpacing}, textScale: .${leaf.textScale})`;
    case 'elevation':
      if (!leaf.shadow) return 'nil';
      return `DSShadow(color: DSColorValue(rgba: ${hex32(leaf.shadow.rgba)}), opacity: ${leaf.shadow.opacity}, radius: ${leaf.shadow.radius}, x: ${leaf.shadow.x}, y: ${leaf.shadow.y})`;
    case 'transition': {
      const [x1, y1, x2, y2] = leaf.easing;
      return `DSTransition(duration: ${r4(leaf.durationMs / 1000)}, delay: ${r4(leaf.delayMs / 1000)}, easing: DSCubicBezier(x1: ${x1}, y1: ${y1}, x2: ${x2}, y2: ${y2}))`;
    }
    case 'fontFamily': {
      const faces = leaf.faces
        .map(
          (f) =>
            `${indent}        DSFontFace(weight: ${f.weight}, postScriptName: ${str(f.postScriptName)}, file: ${str(f.file)})`,
        )
        .join(',\n');
      return `DSFontFamily(\n${indent}    name: ${str(leaf.family)},\n${indent}    faces: [\n${faces}\n${indent}    ]\n${indent})`;
    }
    default:
      throw new Error(`no Swift value for ${leaf.kind}`);
  }
}

/** Constructor expression for a group, recursively. */
function groupValue(node, path, indent) {
  const inner = `${indent}    `;
  const args = [...node.children].map(([name, child]) =>
    isGroup(child)
      ? `${inner}${name}: ${groupValue(child, [...path, name], inner)}`
      : `${inner}${name}: ${leafValue(child, inner)}`,
  );
  return `${typeName(path)}(\n${args.join(',\n')}\n${indent})`;
}

const VALUE_TYPES = `/// An sRGB color as 0xRRGGBBAA. SwiftUI: Color(.sRGB, red:green:blue:opacity:) (PDSUI).
public struct DSColorValue: Sendable, Equatable, Hashable {
    public let rgba: UInt32
    public var red: Double { Double((rgba >> 24) & 0xFF) / 255 }
    public var green: Double { Double((rgba >> 16) & 0xFF) / 255 }
    public var blue: Double { Double((rgba >> 8) & 0xFF) / 255 }
    public var alpha: Double { Double(rgba & 0xFF) / 255 }
}

/// Shape intent instead of a magic radius. \`.full\` → Capsule() / fully rounded corners.
public enum DSCornerShape: String, Sendable, Equatable, CaseIterable {
    case full
}

/// Apple text styles (UIFont.TextStyle names) a typography role scales with under Dynamic Type.
public enum DSTextScale: String, Sendable, Equatable, CaseIterable {
    case largeTitle, title1, title2, title3, headline, body, callout, subheadline, footnote, caption1, caption2
}

/// A typography role. Use Font.custom(postScriptName, size: size, relativeTo: textScale) and
/// scale lineSpacing / tracking with @ScaledMetric(relativeTo:) using the same anchor.
public struct DSTextStyle: Sendable, Equatable {
    /// Family name, e.g. "Inter".
    public let fontFamily: String
    /// The exact face for this weight, e.g. "Inter-SemiBold".
    public let postScriptName: String
    /// 100–900.
    public let fontWeight: Int
    /// Points at the default text size.
    public let size: Double
    /// Absolute line height: size × ratio.
    public let lineHeight: Double
    /// Extra space between lines for SwiftUI .lineSpacing: size × (ratio − 1).
    public let lineSpacing: Double
    /// Letter-spacing as a fraction of the font size (em).
    public let letterSpacing: Double
    /// Points for SwiftUI .tracking: letterSpacing × size.
    public let tracking: Double
    /// Dynamic Type anchor (relativeTo:).
    public let textScale: DSTextScale
}

/// A drop shadow for iOS: .shadow(color: color.opacity(opacity), radius: radius, x: x, y: y),
/// applied to the background shape. Provisional until Phase 5 visual validation.
public struct DSShadow: Sendable, Equatable {
    /// Opaque shadow color; apply \`opacity\` on top.
    public let color: DSColorValue
    public let opacity: Double
    public let radius: Double
    public let x: Double
    public let y: Double
}

/// A cubic-bezier timing curve. SwiftUI: Animation.timingCurve(x1, y1, x2, y2, duration:).
public struct DSCubicBezier: Sendable, Equatable {
    public let x1: Double
    public let y1: Double
    public let x2: Double
    public let y2: Double
}

/// A transition. Durations in seconds. Respect \\.accessibilityReduceMotion at runtime.
public struct DSTransition: Sendable, Equatable {
    public let duration: Double
    public let delay: Double
    public let easing: DSCubicBezier
}

/// One font face (asset metadata — no font files ship with the tokens).
public struct DSFontFace: Sendable, Equatable {
    public let weight: Int
    public let postScriptName: String
    public let file: String
}

/// The faces one font role needs. If a face isn't registered, fall back to the system font at
/// the same size and Dynamic Type anchor with the role's weight — never another brand's family.
public struct DSFontFamily: Sendable, Equatable {
    public let name: String
    public let faces: [DSFontFace]
}
`;

/** @returns {Record<string, string>} relative file path → contents */
export function emitSwift(models) {
  const reference = models.find((m) => m.default) ?? models[0];

  const groups = [[[], reference.root]];
  walk(reference.root, [], (p, g) => groups.push([p, g]));
  const names = new Set();
  let types = '';
  for (const [path, group] of groups) {
    const name = typeName(path);
    if (names.has(name)) throw new Error(`Swift type name collision: ${name}`);
    names.add(name);
    types += `\npublic struct ${name}: Sendable, Equatable {\n`;
    for (const [field, child] of group.children) {
      if (isGroup(child)) types += `    public let ${id(field)}: ${typeName([...path, field])}\n`;
      else
        types += `${doc(child.description, '    ')}    public let ${id(field)}: ${leafType(child)}\n`;
    }
    types += '}\n';
  }

  const files = {};
  files['DSTheme.swift'] = `${HEADER}
${VALUE_TYPES}
// MARK: - Token groups
${types}
// MARK: - Themes

extension DSTheme {
    /// Every brand's theme by brand name (runtime brand selection).
    public static let all: [String: DSTheme] = [
${models.map((m) => `        ${str(m.brand)}: .${brandConst(m.brand)}`).join(',\n')}
    ]
    /// The default brand's name.
    public static let defaultBrandName = ${str(reference.brand)}
}
`;
  for (const m of models) {
    const file = `DSTheme+${pascal(brandConst(m.brand))}.swift`;
    files[file] = `${HEADER}
extension DSTheme {
    /// ${m.brand}${m.default ? ' (default)' : ''}.
    public static let ${brandConst(m.brand)} = ${groupValue(m.root, [], '    ')}
}
`;
  }
  return files;
}
