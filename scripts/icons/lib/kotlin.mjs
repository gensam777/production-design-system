/**
 * Compose icon generator (ADR 0019 rule 2): the catalog (design/icons/icons.json) + the Lucide
 * artwork at the pinned version (lucide-static/icon-nodes.json) → Kotlin sources committed in
 * platforms/android/compose/src/main/kotlin/com/pds/compose/icons/:
 *
 *   DsIconName.kt    public enum, one entry per catalog name (`id` = the catalog name)
 *   LucideIcons.kt   internal ImageVector per icon, in Lucide's 24×24 viewport
 *
 * Every SVG element becomes path data normalized to move / line / cubic / close (./svg.mjs),
 * so Compose needs no SVG parsing. Pure functions — scripts/icons/generate-kotlin.mjs writes
 * the files, icons:test checks they are current.
 */
import { normalizePath } from './svg.mjs';

export const KOTLIN_DIR = 'platforms/android/compose/src/main/kotlin/com/pds/compose/icons';
export const KOTLIN_ENUM = `${KOTLIN_DIR}/DsIconName.kt`;
export const KOTLIN_VECTORS = `${KOTLIN_DIR}/LucideIcons.kt`;

/** `arrow-left` → `ArrowLeft` (Kotlin enum entry). */
export const kotlinEntry = (name) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

/** One Lucide node ([tag, attrs]) → equivalent SVG path data. */
export function elementPathData([tag, a]) {
  const n = (k) => Number(a[k] ?? 0);
  switch (tag) {
    case 'path':
      return a.d;
    case 'circle':
    case 'ellipse': {
      const rx = tag === 'circle' ? n('r') : n('rx');
      const ry = tag === 'circle' ? n('r') : n('ry');
      const cx = n('cx');
      const cy = n('cy');
      return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
    }
    case 'rect': {
      const x = n('x');
      const y = n('y');
      const w = n('width');
      const h = n('height');
      const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx || !ry) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
      return (
        `M${x + rx} ${y}H${x + w - rx}A${rx} ${ry} 0 0 1 ${x + w} ${y + ry}` +
        `V${y + h - ry}A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h}` +
        `H${x + rx}A${rx} ${ry} 0 0 1 ${x} ${y + h - ry}` +
        `V${y + ry}A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`
      );
    }
    case 'line':
      return `M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`;
    case 'polyline':
    case 'polygon': {
      const v = String(a.points)
        .trim()
        .split(/[\s,]+/)
        .map(Number);
      let d = '';
      for (let k = 0; k < v.length; k += 2) d += `${k === 0 ? 'M' : 'L'}${v[k]} ${v[k + 1]}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    default:
      throw new Error(`unsupported Lucide element <${tag}>`);
  }
}

const f = (v) => {
  const r = Math.round(v * 1e4) / 1e4;
  return `${Object.is(r, -0) ? 0 : r}f`;
};

/** One Lucide node → PathBuilder statements. */
export function kotlinStatements(node) {
  return normalizePath(elementPathData(node)).map((c) =>
    c.op === 'M'
      ? `moveTo(${f(c.x)}, ${f(c.y)})`
      : c.op === 'L'
        ? `lineTo(${f(c.x)}, ${f(c.y)})`
        : c.op === 'C'
          ? `curveTo(${f(c.c1x)}, ${f(c.c1y)}, ${f(c.c2x)}, ${f(c.c2y)}, ${f(c.x)}, ${f(c.y)})`
          : 'close()',
  );
}

const HEADER = `// Generated by scripts/icons/generate-kotlin.mjs from design/icons/icons.json — do not edit.
// Regenerate: npm run icons:kotlin. Checked by npm run icons:test (ADR 0019).
`;

/**
 * @param manifest design/icons/icons.json
 * @param nodes lucide-static/icon-nodes.json at manifest.provider.version
 * @param license the Lucide licence text
 * @returns {Map<string, string>} repo path → file content
 */
export function generateKotlin(manifest, nodes, license) {
  const icons = Object.entries(manifest.icons);
  const { version, viewBox, strokeWidth } = manifest.provider;

  const entries = icons
    .map(
      ([name, { description, lucide }]) =>
        `    /** ${description} Lucide \`${lucide}\`. */\n    ${kotlinEntry(name)}("${name}"),`,
    )
    .join('\n');
  const enumFile = `${HEADER}
package com.pds.compose.icons

/**
 * A name from the shared icon catalog (design/icons/icons.json, ADR 0019) — the only icon names a
 * com.pds.compose component accepts. [id] is the catalog name, identical on every platform (web /
 * React Native \`IconName\`, SwiftUI \`DSIconName\`). Icons are decorative: the owning control
 * provides the accessible name.
 */
enum class DsIconName(val id: String) {
${entries}
    ;

    companion object {
        /** The entry for a catalog name, or null. */
        fun fromId(id: String): DsIconName? = entries.firstOrNull { it.id == id }
    }
}
`;

  const branches = icons
    .map(([name, { lucide }]) => {
      const node = nodes[lucide];
      if (!node) throw new Error(`lucide-static has no icon '${lucide}' (catalog '${name}')`);
      const paths = node
        .map((el) => {
          const body = kotlinStatements(el)
            .map((s) => `            ${s}`)
            .join('\n');
          return `        stroke {\n${body}\n        }`;
        })
        .join('\n');
      return `    DsIconName.${kotlinEntry(name)} -> {\n${paths}\n    }`;
    })
    .join('\n');
  const licenseComment = license
    .trim()
    .split('\n')
    .map((l) => (l ? `// ${l}` : '//'))
    .join('\n');
  const vectorsFile = `${HEADER}//
// Artwork: Lucide ${version} (lucide-static), converted to Compose ImageVectors in its
// ${viewBox}×${viewBox} viewport. Stroke-only: stroke ${strokeWidth}, round caps and joins; tint at draw time.
//
${licenseComment}

package com.pds.compose.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathBuilder
import androidx.compose.ui.unit.dp

/** The Lucide artwork of a catalog icon, built once per icon. */
internal val DsIconName.lucideVector: ImageVector
    get() = lucideVectors.getValue(this)

private val lucideVectors: Map<DsIconName, ImageVector> by lazy {
    DsIconName.entries.associateWith { name ->
        ImageVector.Builder(
            name = "Lucide.\${name.id}",
            defaultWidth = ${viewBox}.dp,
            defaultHeight = ${viewBox}.dp,
            viewportWidth = ${viewBox}f,
            viewportHeight = ${viewBox}f,
        ).apply { lucidePaths(name) }.build()
    }
}

private inline fun ImageVector.Builder.stroke(block: PathBuilder.() -> Unit) {
    addPath(
        pathData = PathBuilder().apply(block).nodes,
        fill = null,
        stroke = SolidColor(Color.Black),
        strokeLineWidth = ${strokeWidth}f,
        strokeLineCap = StrokeCap.Round,
        strokeLineJoin = StrokeJoin.Round,
    )
}

private fun ImageVector.Builder.lucidePaths(name: DsIconName) = when (name) {
${branches}
}
`;
  return new Map([
    [KOTLIN_ENUM, enumFile],
    [KOTLIN_VECTORS, vectorsFile],
  ]);
}

/** Catalog ids in `enum class DsIconName` (`Entry("id")`). */
export function parseKotlinIconNames(source) {
  const m = source.match(/enum\s+class\s+DsIconName\b[^{]*\{([\s\S]*?)\n\s*;/);
  return m ? [...m[1].matchAll(/^\s*[A-Z][A-Za-z0-9]*\("([^"]+)"\)/gm)].map((x) => x[1]) : null;
}
