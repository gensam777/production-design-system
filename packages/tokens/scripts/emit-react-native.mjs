/**
 * React Native emitter (ADR 0016) — one TypeScript module with a `Theme` type and one theme
 * object per brand, from the native model (packages/tokens/scripts/native.mjs). Pure data: no
 * `react-native` import, so it type-checks and tests without React Native installed.
 *
 *   color       '#RRGGBB' / '#RRGGBBAA' strings (React Native accepts both)
 *   space, radius, icon   numbers (dp/pt); `radius.full` → 9999 (RN has no capsule shape)
 *   typography  style-safe objects { fontFamily: <PostScript name>, fontSize, lineHeight,
 *               letterSpacing } — absolute values; no fontWeight, because the face is already
 *               the exact weight (Android would otherwise synthesize bold)
 *   dynamicTypeRamp  iOS <Text dynamicTypeRamp> per typography role (a prop, not a style)
 *   elevation   one style object for both platforms: iOS shadow* + Android `elevation`
 *   motion      { duration, delay } in ms + cubic-bezier `easing`
 *   fonts       per-role family, faces and system fallback (asset metadata)
 */
import { isGroup, walk } from './native.mjs';

const HEADER = `// Generated by packages/tokens/scripts/emit-react-native.mjs from the token IR — do not edit.
// Semantic and component-scoped tokens only; Core and brand.* tokens stay internal
// (ADR 0013, 0014, 0016). Source: design/tokens/. Rebuild: npm run tokens:build.
`;

/** System fallback per font role when a face isn't loaded (ADR 0016). */
export const RN_FONT_FALLBACK = {
  sans: { ios: 'System', android: 'sans-serif' },
  mono: { ios: 'Menlo', android: 'monospace' },
};

const str = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const doc = (text, indent) =>
  text
    ? `${indent}/** ${String(text).replace(/\s+/g, ' ').replace(/\*\//g, '* /').trim()} */\n`
    : '';
const num = (n) => String(n);

const brandConst = (brand) => brand.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function leafType(leaf) {
  switch (leaf.kind) {
    case 'color':
      return 'string';
    case 'dimension':
    case 'shape':
      return 'number';
    case 'textStyle':
      return 'TextStyleToken';
    case 'elevation':
      return 'ElevationStyle';
    case 'transition':
      return 'Transition';
    case 'fontFamily':
      return 'FontFamilyToken';
    default:
      throw new Error(`no React Native type for ${leaf.kind}`);
  }
}

function leafValue(leaf, indent) {
  const i2 = `${indent}  `;
  switch (leaf.kind) {
    case 'color':
      return str(leaf.hex);
    case 'dimension':
    case 'shape':
      return num(leaf.value);
    case 'textStyle':
      return `{ fontFamily: ${str(leaf.postScriptName)}, fontSize: ${leaf.fontSize}, lineHeight: ${leaf.lineHeight}, letterSpacing: ${leaf.letterSpacing} }`;
    case 'elevation': {
      const s = leaf.shadow ?? { color: '#000000', opacity: 0, radius: 0, x: 0, y: 0 };
      return `{ shadowColor: ${str(s.color)}, shadowOffset: { width: ${s.x}, height: ${s.y} }, shadowOpacity: ${s.opacity}, shadowRadius: ${s.radius}, elevation: ${leaf.height} }`;
    }
    case 'transition':
      return `{ duration: ${leaf.durationMs}, delay: ${leaf.delayMs}, easing: [${leaf.easing.join(', ')}] }`;
    case 'fontFamily': {
      const faces = leaf.faces
        .map(
          (f) =>
            `${i2}  { weight: ${f.weight}, postScriptName: ${str(f.postScriptName)}, file: ${str(f.file)} },`,
        )
        .join('\n');
      const fb = RN_FONT_FALLBACK[leaf.role];
      return `{\n${i2}family: ${str(leaf.family)},\n${i2}faces: [\n${faces}\n${i2}],\n${i2}fallback: { ios: ${str(fb.ios)}, android: ${str(fb.android)} },\n${indent}}`;
    }
    default:
      throw new Error(`no React Native value for ${leaf.kind}`);
  }
}

function typeBody(node, indent) {
  let out = '';
  for (const [name, child] of node.children) {
    if (isGroup(child))
      out += `${indent}readonly ${name}: {\n${typeBody(child, `${indent}  `)}${indent}};\n`;
    else out += `${doc(child.description, indent)}${indent}readonly ${name}: ${leafType(child)};\n`;
  }
  return out;
}

function valueBody(node, indent) {
  let out = '';
  for (const [name, child] of node.children) {
    if (isGroup(child))
      out += `${indent}${name}: {\n${valueBody(child, `${indent}  `)}${indent}},\n`;
    else out += `${indent}${name}: ${leafValue(child, indent)},\n`;
  }
  return out;
}

/** `dynamicTypeRamp` tree: typography role (without weight) → iOS text style. */
function rampTree(model) {
  const tree = { kind: 'group', children: new Map() };
  walk(model.root, [], null, (p, leaf) => {
    if (leaf.kind !== 'textStyle') return;
    const segs = p.slice(1, -1);
    let node = tree;
    for (const s of segs.slice(0, -1)) {
      if (!node.children.has(s)) node.children.set(s, { kind: 'group', children: new Map() });
      node = node.children.get(s);
    }
    node.children.set(segs.at(-1), { kind: 'ramp', value: leaf.textScale });
  });
  return tree;
}
const rampBody = (node, indent, asType) => {
  let out = '';
  for (const [name, child] of node.children) {
    if (isGroup(child))
      out += `${indent}${asType ? 'readonly ' : ''}${name}: {\n${rampBody(child, `${indent}  `, asType)}${indent}}${asType ? ';' : ','}\n`;
    else
      out += asType
        ? `${indent}readonly ${name}: DynamicTypeRamp;\n`
        : `${indent}${name}: ${str(child.value)},\n`;
  }
  return out;
};

/** @returns {Record<string, string>} relative file path → contents */
export function emitReactNative(models) {
  const reference = models.find((m) => m.default) ?? models[0];
  const brands = models.map((m) => m.brand);
  const ramp = rampTree(reference);

  let out = `${HEADER}
export type BrandName = ${brands.map(str).join(' | ')};

/** iOS Dynamic Type text styles (React Native \`<Text dynamicTypeRamp>\`, RN ≥ 0.72). */
export type DynamicTypeRamp =
  | 'largeTitle'
  | 'title1'
  | 'title2'
  | 'title3'
  | 'headline'
  | 'body'
  | 'callout'
  | 'subheadline'
  | 'footnote'
  | 'caption1'
  | 'caption2';

/** A typography role as a React Native text style. \`fontFamily\` is the face's PostScript
 * name (one face per weight), so no \`fontWeight\` is set. Values are absolute and scale with
 * the OS text size (\`allowFontScaling\`); pair with \`dynamicTypeRamp\` on iOS. */
export interface TextStyleToken {
  readonly fontFamily: string;
  readonly fontSize: number;
  /** fontSize × line-height ratio. */
  readonly lineHeight: number;
  /** em × fontSize. */
  readonly letterSpacing: number;
}

/** Elevation as one style object: iOS reads shadow*, Android reads \`elevation\` (dp).
 * Android values are provisional until Phase 5 visual validation (ADR 0016). */
export interface ElevationStyle {
  readonly shadowColor: string;
  readonly shadowOffset: { readonly width: number; readonly height: number };
  readonly shadowOpacity: number;
  readonly shadowRadius: number;
  readonly elevation: number;
}

/** Durations in ms; easing is a cubic-bezier [x1, y1, x2, y2]. Respect
 * \`AccessibilityInfo.isReduceMotionEnabled()\` at runtime. */
export interface Transition {
  readonly duration: number;
  readonly delay: number;
  readonly easing: readonly [number, number, number, number];
}

export interface FontFaceToken {
  readonly weight: number;
  readonly postScriptName: string;
  readonly file: string;
}

/** Font asset metadata for one font role. No font files ship with the tokens; if a face isn't
 * loaded, use \`fallback\` for the platform (and set fontWeight) — never another brand's family. */
export interface FontFamilyToken {
  readonly family: string;
  readonly faces: readonly FontFaceToken[];
  readonly fallback: { readonly ios: string; readonly android: string };
}

export interface Theme {
${typeBody(reference.root, '  ')}  readonly dynamicTypeRamp: {
${rampBody(ramp, '    ', true)}  };
}
`;
  for (const m of models) {
    out += `
/** ${m.brand}${m.default ? ' (default)' : ''}. */
export const ${brandConst(m.brand)}: Theme = {
${valueBody(m.root, '  ')}  dynamicTypeRamp: {
${rampBody(rampTree(m), '    ', false)}  },
};
`;
  }
  out += `
export const themes: Readonly<Record<BrandName, Theme>> = {
${models.map((m) => `  ${str(m.brand)}: ${brandConst(m.brand)},`).join('\n')}
};

export const defaultBrand: BrandName = ${str(reference.brand)};
`;
  return { 'index.ts': out };
}
