/**
 * Kotlin emitter (ADR 0016) — package `com.pds.tokens`: value types, one generated data class
 * per token group, and one `DsTheme` per brand, from the native model (packages/tokens/scripts/native.mjs).
 *
 * Plain Kotlin (no Android / Compose dependency), so it compiles with `kotlinc` alone in CI.
 * Values are Compose-ready primitives; the Compose adapters (Color, Dp, TextStyle, FontFamily,
 * Shape, tween) belong to com.pds.compose (Phase 5):
 *
 *   color       DsColorValue(argb = 0xAARRGGBB) → Color(argb)
 *   space, radius, icon   Float dp; `radius.full` → DsCornerShape.Full (CircleShape / 50 %)
 *   typography  DsTextStyle — face, fontSize (sp), lineHeight and letterSpacing in em
 *               (lineHeight = ratio.em keeps the ratio under nonlinear font scaling)
 *   elevation   Float dp — Android's native elevation (Surface shadowElevation), provisional
 *   motion      DsTransition — ms + cubic-bezier → tween(durationMillis, delayMillis, CubicBezierEasing)
 *   fonts       DsFontFamily per font role (asset metadata incl. res/font resource names)
 */
import { isGroup, pascal, walk } from './native.mjs';

const HEADER = `// Generated by packages/tokens/scripts/emit-kotlin.mjs from the token IR — do not edit.
// com.pds.tokens: semantic and component-scoped tokens only; Core and brand.* tokens stay
// internal (ADR 0013, 0014, 0016). Source: design/tokens/. Rebuild: npm run tokens:build.
`;

const KEYWORDS = new Set(
  'as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while'.split(
    ' ',
  ),
);
const id = (name) => (KEYWORDS.has(name) ? `\`${name}\`` : name);
const str = (s) =>
  `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const doc = (text, indent) =>
  text
    ? `${indent}/** ${String(text).replace(/\s+/g, ' ').replace(/\*\//g, '* /').trim()} */\n`
    : '';
const f = (n) => `${n}f`;
const hexLong = (n) => `0x${n.toString(16).toUpperCase().padStart(8, '0')}L`;
const brandConst = (brand) => pascal(brand.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()));
const typeName = (path) => (path.length ? `Ds${path.map(pascal).join('')}` : 'DsTheme');

function leafType(leaf) {
  switch (leaf.kind) {
    case 'color':
      return 'DsColorValue';
    case 'dimension':
    case 'elevation':
      return 'Float';
    case 'shape':
      return 'DsCornerShape';
    case 'textStyle':
      return 'DsTextStyle';
    case 'transition':
      return 'DsTransition';
    case 'fontFamily':
      return 'DsFontFamily';
    default:
      throw new Error(`no Kotlin type for ${leaf.kind}`);
  }
}

function leafValue(leaf, indent) {
  switch (leaf.kind) {
    case 'color':
      return `DsColorValue(${hexLong(leaf.argb)})`;
    case 'dimension':
      return f(leaf.value);
    case 'elevation':
      return f(leaf.height);
    case 'shape':
      return `DsCornerShape.${pascal(leaf.shape)}`;
    case 'textStyle':
      return `DsTextStyle(fontFamily = ${str(leaf.fontFamily)}, postScriptName = ${str(leaf.postScriptName)}, fontResourceName = ${str(leaf.androidResource)}, fontWeight = ${leaf.fontWeight}, fontSize = ${f(leaf.fontSize)}, lineHeight = ${f(leaf.lineHeightRatio)}, letterSpacing = ${f(leaf.letterSpacingEm)})`;
    case 'transition': {
      const [x1, y1, x2, y2] = leaf.easing.map(f);
      return `DsTransition(durationMillis = ${leaf.durationMs}, delayMillis = ${leaf.delayMs}, easing = DsCubicBezier(${x1}, ${y1}, ${x2}, ${y2}))`;
    }
    case 'fontFamily': {
      const faces = leaf.faces
        .map(
          (x) =>
            `${indent}        DsFontFace(weight = ${x.weight}, postScriptName = ${str(x.postScriptName)}, file = ${str(x.file)}, resourceName = ${str(x.androidResource)}),`,
        )
        .join('\n');
      return `DsFontFamily(\n${indent}    name = ${str(leaf.family)},\n${indent}    faces = listOf(\n${faces}\n${indent}    ),\n${indent})`;
    }
    default:
      throw new Error(`no Kotlin value for ${leaf.kind}`);
  }
}

function groupValue(node, path, indent) {
  const inner = `${indent}    `;
  const args = [...node.children].map(([name, child]) =>
    isGroup(child)
      ? `${inner}${id(name)} = ${groupValue(child, [...path, name], inner)},`
      : `${inner}${id(name)} = ${leafValue(child, inner)},`,
  );
  return `${typeName(path)}(\n${args.join('\n')}\n${indent})`;
}

const VALUE_TYPES = `/** An sRGB color as 0xAARRGGBB. Compose: Color(argb). */
data class DsColorValue(val argb: Long)

/** Shape intent instead of a magic radius. Full → CircleShape / RoundedCornerShape(50). */
enum class DsCornerShape { Full }

/**
 * A typography role. Compose: TextStyle(fontFamily = <family for postScriptName>, fontWeight =
 * FontWeight(fontWeight), fontSize = fontSize.sp, lineHeight = lineHeight.em, letterSpacing =
 * letterSpacing.em, lineHeightStyle = LineHeightStyle(Center, Trim.None)).
 */
data class DsTextStyle(
    /** Family name, e.g. "Inter". */
    val fontFamily: String,
    /** The exact face for this weight, e.g. "Inter-SemiBold". */
    val postScriptName: String,
    /** res/font resource name of the face, e.g. "inter_semibold". */
    val fontResourceName: String,
    /** 100–900. */
    val fontWeight: Int,
    /** sp. */
    val fontSize: Float,
    /** Line height as a multiple of the font size (em). */
    val lineHeight: Float,
    /** Letter-spacing as a fraction of the font size (em). */
    val letterSpacing: Float,
)

/** A cubic-bezier timing curve. Compose: CubicBezierEasing(x1, y1, x2, y2). */
data class DsCubicBezier(val x1: Float, val y1: Float, val x2: Float, val y2: Float)

/** A transition. Compose: tween(durationMillis, delayMillis, easing). The system animator
 * duration scale handles reduced motion. */
data class DsTransition(val durationMillis: Int, val delayMillis: Int, val easing: DsCubicBezier)

/** One font face (asset metadata — no font files ship with the tokens). */
data class DsFontFace(val weight: Int, val postScriptName: String, val file: String, val resourceName: String)

/** The faces one font role needs. If a face is unavailable, fall back to FontFamily.Default /
 * FontFamily.Monospace with the same weight — never another brand's family. */
data class DsFontFamily(val name: String, val faces: List<DsFontFace>)
`;

/** @returns {Record<string, string>} relative file path → contents */
export function emitKotlin(models) {
  const reference = models.find((m) => m.default) ?? models[0];

  const groups = [[[], reference.root]];
  walk(reference.root, [], (p, g) => groups.push([p, g]));
  const names = new Set();
  let types = '';
  for (const [path, group] of groups) {
    const name = typeName(path);
    if (names.has(name)) throw new Error(`Kotlin type name collision: ${name}`);
    names.add(name);
    types += `\ndata class ${name}(\n`;
    for (const [field, child] of group.children) {
      if (isGroup(child)) types += `    val ${id(field)}: ${typeName([...path, field])},\n`;
      else {
        const unit =
          child.kind === 'elevation'
            ? 'Android elevation, dp. Provisional until Phase 5 visual validation.'
            : '';
        types += `${doc([child.description, unit].filter(Boolean).join(' '), '    ')}    val ${id(field)}: ${leafType(child)},\n`;
      }
    }
    types += ')\n';
  }

  const files = {};
  files['DsTheme.kt'] = `${HEADER}
package com.pds.tokens

${VALUE_TYPES}
// Token groups
${types}
/** Every brand's theme by brand name (runtime brand selection). */
object DsThemes {
    const val DEFAULT_BRAND: String = ${str(reference.brand)}

    val all: Map<String, DsTheme> by lazy {
        mapOf(
${models.map((m) => `            ${str(m.brand)} to ${brandConst(m.brand)},`).join('\n')}
        )
    }
}
`;
  for (const m of models) {
    files[`${brandConst(m.brand)}.kt`] = `${HEADER}
package com.pds.tokens

/** ${m.brand}${m.default ? ' (default)' : ''}. */
val ${brandConst(m.brand)}: DsTheme = ${groupValue(m.root, [], '')}
`;
  }
  return files;
}
